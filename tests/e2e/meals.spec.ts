import { test, expect, type Page } from '@playwright/test';
test.use({ timezoneId: 'Australia/Brisbane' });
const original = { id: 'original', date: '2026-01-01', name: 'Breakfast oats', calories: 380, protein: 13, carbs: 60, fats: 7, confidence: 0.5, pantryItemId: 'oats' };
async function dismiss(page: Page) {
  await page.getByRole('button', { name: /Skip for now/ }).click();
  await expect(page.getByTestId('today-screen')).toBeVisible();
}
async function seed(page: Page, extra: Record<string, unknown> = {}) {
  await page.goto('/'); await dismiss(page);
  await page.evaluate(async ({ food, extra }) => {
    const { storage } = await import(/* @vite-ignore */ String('/services/storageService.ts'));
    await storage.overwriteEverything({ ironflow_fuel: [food], ...extra });
  }, { food: original, extra });
  await page.reload(); await dismiss(page);
  await page.getByRole('button', { name: 'Food', exact: true }).click();
}
async function record(page: Page, key = 'ironflow_fuel') {
  return page.evaluate(async key => {
    const { storage } = await import(/* @vite-ignore */ String('/services/storageService.ts'));
    return storage.get(key);
  }, key);
}
test('repeat a historical meal with reviewed quantity and local date, preserving its source offline', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await seed(page);
  await page.getByRole('button', { name: /Thu, Jan 1/ }).click();
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Repeat Breakfast oats', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Log meal', exact: true });
  await dialog.getByText('Adjust amount', { exact: false }).first().click();
  await dialog.getByLabel('Amount multiplier for Breakfast oats').fill('0.5');
  await dialog.getByLabel('Date', { exact: true }).fill('2026-10-25');
  await expect(dialog).toContainText('Total: 190 kcal');
  await dialog.getByRole('button', { name: 'Add to food log' }).click();
  await expect.poll(async () => ((await record(page)) as any[])?.length).toBe(2);
  const logs = (await record(page)) as any[];
  expect(logs.find(log => log.id === 'original')).toEqual(original);
  expect(logs.find(log => log.id !== 'original')).toMatchObject({ date: '2026-10-25', calories: 190, protein: 6.5, confidence: 0.5, pantryItemId: 'oats' });
  await context.setOffline(false);
  await page.reload(); await dismiss(page);
  expect(((await record(page)) as any[]).length).toBe(2);
});
