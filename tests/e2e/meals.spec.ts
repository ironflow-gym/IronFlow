test('create a grouped meal, log reviewed portions offline, edit and delete without changing food history', async ({ page, context }) => {
  await page.setViewportSize({ width: 360, height: 640 });
  const coffee = { ...original, id: 'coffee', name: 'Coffee', calories: 80, protein: 4, carbs: 6, fats: 4, confidence: 1 };
  await seed(page, { ironflow_fuel: [original, coffee] });
  await page.getByRole('button', { name: 'Create saved meal', exact: true }).click();
  let editor = page.getByRole('dialog', { name: 'Save meal', exact: true });
  await editor.getByLabel('Meal name', { exact: true }).fill('Usual breakfast');
  await editor.getByRole('checkbox', { name: /Breakfast oats/ }).check();
  await editor.getByRole('checkbox', { name: /Coffee/ }).check();
  await editor.getByRole('button', { name: 'Save meal', exact: true }).click();
  await expect.poll(async () => ((await record(page, 'ironflow_saved_meals')) as any[])?.length).toBe(1);
  const snapshot = (await record(page, 'ironflow_saved_meals')) as any[];
  expect(snapshot[0].foods).toHaveLength(2);
  expect(await record(page)).toEqual([original, coffee]);
  const list = page.getByRole('dialog', { name: 'Saved meals', exact: true });
  await context.setOffline(true);
  await list.getByRole('button', { name: 'Log Usual breakfast', exact: true }).click();
  const logging = page.getByRole('dialog', { name: 'Log meal', exact: true });
  await logging.getByText('Adjust amount for Coffee', { exact: true }).click();
  await logging.getByRole('group', { name: 'Amount shortcuts for Coffee' }).getByRole('button', { name: 'Double', exact: true }).click();
  await logging.getByLabel('Date', { exact: true }).fill('2026-10-26');
  await expect(logging).toContainText('Total: 540 kcal');
  const box = (await logging.getByRole('button', { name: 'Add to food log' }).boundingBox())!;
  expect(box.y + box.height).toBeLessThanOrEqual(640);
  await logging.getByRole('button', { name: 'Add to food log' }).click();
  await expect.poll(async () => ((await record(page)) as any[])?.length).toBe(4);
  const logged = (await record(page)) as any[];
  expect(logged.filter(log => log.date === '2026-10-26').map(log => log.calories)).toEqual([380, 160]);
  expect(await record(page, 'ironflow_saved_meals')).toEqual(snapshot);
  await list.getByText('Options for Usual breakfast', { exact: true }).click();
  await list.getByRole('button', { name: 'Edit saved meal Usual breakfast', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'Save meal', exact: true });
  await editor.getByLabel('Meal name', { exact: true }).fill('Breakfast favourite');
  await editor.getByText('Adjust amount for Coffee', { exact: true }).click();
  await editor.getByRole('button', { name: 'Remove Coffee from saved meal' }).click();
  await editor.getByText('Adjust amount for Breakfast oats', { exact: true }).click();
  await editor.getByLabel('Amount multiplier for Breakfast oats').fill('0.5');
  await editor.getByRole('button', { name: 'Save meal', exact: true }).click();
  await expect.poll(async () => ((await record(page, 'ironflow_saved_meals')) as any[])?.[0]?.name).toBe('Breakfast favourite');
  expect(((await record(page, 'ironflow_saved_meals')) as any[])[0].foods[0].calories).toBe(190);
  expect(await record(page)).toEqual(logged);
  await list.getByRole('button', { name: 'Delete saved meal Breakfast favourite' }).click();
  await page.getByRole('dialog', { name: 'Delete saved meal' }).getByRole('button', { name: 'Cancel', exact: true }).click();
  expect(((await record(page, 'ironflow_saved_meals')) as any[]).length).toBe(1);
  await list.getByRole('button', { name: 'Delete saved meal Breakfast favourite' }).click();
  await page.getByRole('dialog', { name: 'Delete saved meal' }).getByRole('button', { name: 'Delete saved meal', exact: true }).click();
  await expect.poll(async () => (await record(page, 'ironflow_saved_meals'))).toEqual([]);
  expect(await record(page)).toEqual(logged);
  await context.setOffline(false);
  await page.reload(); await dismiss(page);
  expect(await record(page, 'ironflow_saved_meals')).toEqual([]);
});

test('single saved meal exports and restores, and older backups load without saved meals', async ({ page }) => {
  await seed(page);
  await page.getByRole('button', { name: 'Create saved meal', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Save meal', exact: true });
  await editor.getByLabel('Meal name', { exact: true }).fill('Oats favourite');
  await editor.getByRole('checkbox', { name: /Breakfast oats/ }).check();
  await editor.getByRole('button', { name: 'Save meal', exact: true }).click();
  await page.getByRole('button', { name: 'Close saved meals', exact: true }).click();
  await page.getByRole('button', { name: 'Vault Backup', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: /Export Local Vault/ }).click();
  const stream = await (await downloadPromise).createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const exported = JSON.parse(Buffer.concat(chunks).toString());
  expect(exported.ironflow_saved_meals[0].name).toBe('Oats favourite');
  expect(exported.ironflow_saved_meals[0].foods[0].confidence).toBe(0.5);
  await page.locator('input[type=file]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) });
  await page.getByRole('button', { name: 'Confirm Neural Sync', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Neural Core Re-initialized', exact: true })).toBeVisible();
  expect(await record(page, 'ironflow_saved_meals')).toEqual(exported.ironflow_saved_meals);
  await page.reload(); await dismiss(page);
  await page.getByRole('button', { name: 'Food', exact: true }).click();
  await page.getByRole('button', { name: 'View saved meals (1)' }).click();
  await expect(page.getByRole('button', { name: 'Log Oats favourite' })).toBeVisible();
  await page.getByRole('button', { name: 'Close saved meals', exact: true }).click();
  await page.getByRole('button', { name: 'Vault Backup', exact: true }).click();
  delete exported.ironflow_saved_meals;
  await page.locator('input[type=file]').setInputFiles({ name: 'old.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) });
  await page.getByRole('button', { name: 'Confirm Neural Sync', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Neural Core Re-initialized', exact: true })).toBeVisible();
  await page.reload(); await dismiss(page);
  await page.getByRole('button', { name: 'Food', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Create saved meal', exact: true })).toBeVisible();
});

test('saved meal cancellation writes nothing and a failed save can be retried without losing the meal', async ({ page }) => {
  await seed(page);
  await page.getByRole('button', { name: 'Create saved meal', exact: true }).click();
  let editor = page.getByRole('dialog', { name: 'Save meal', exact: true });
  await editor.getByLabel('Meal name', { exact: true }).fill('Cancelled breakfast');
  await page.keyboard.press('Escape');
  expect(await record(page, 'ironflow_saved_meals')).toBeNull();
  await page.getByRole('dialog', { name: 'Saved meals', exact: true }).getByRole('button', { name: 'Create saved meal', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'Save meal', exact: true });
  await editor.getByLabel('Meal name', { exact: true }).fill('Retry breakfast');
  await editor.getByRole('checkbox', { name: /Breakfast oats/ }).check();
  await page.evaluate(() => {
    const originalPut = IDBObjectStore.prototype.put;
    (window as any).__restorePut = () => { IDBObjectStore.prototype.put = originalPut; };
    IDBObjectStore.prototype.put = function (...args: Parameters<typeof originalPut>) {
      if (args[0].id === 'ironflow_saved_meals') throw new DOMException('Storage full', 'QuotaExceededError');
      return originalPut.apply(this, args);
    };
  });
  await editor.getByRole('button', { name: 'Save meal', exact: true }).click();
  await page.getByRole('button', { name: 'Close saved meals', exact: true }).click();
  await expect(page.getByText('Not saved — keep this tab open', { exact: true })).toBeVisible();
  expect(await record(page, 'ironflow_saved_meals')).toBeNull();
  expect(await record(page)).toEqual([original]);
  await page.evaluate(() => (window as any).__restorePut());
  await page.getByRole('button', { name: 'Retry save', exact: true }).click();
  await expect.poll(async () => ((await record(page, 'ironflow_saved_meals')) as any[])?.[0]?.name).toBe('Retry breakfast');
  await page.reload(); await dismiss(page);
  expect(((await record(page, 'ironflow_saved_meals')) as any[])[0].foods[0].calories).toBe(380);
});

test('checked foods across dates are included immediately, and unchecking removes them before save', async ({ page }) => {
  const coffee = { ...original, id: 'coffee', date: '2026-01-02', name: 'Coffee', calories: 80 };
  await seed(page, { ironflow_fuel: [original, coffee] });
  await page.getByRole('button', { name: 'Create saved meal', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Save meal', exact: true });
  await editor.getByLabel('Meal name', { exact: true }).fill('Across dates');
  await editor.getByRole('checkbox', { name: /Coffee/ }).check();
  await expect(editor.getByRole('region', { name: 'Foods in saved meal' })).toContainText('Coffee');
  await editor.getByLabel('Food log date').selectOption('2026-01-01');
  const oats = editor.getByRole('checkbox', { name: /Breakfast oats/ });
  await oats.check();
  await expect(editor.getByRole('status')).toContainText('Total: 460 kcal');
  await oats.uncheck();
  await expect(editor.getByRole('status')).toContainText('Total: 80 kcal');
  await editor.getByLabel('Food log date').selectOption('2026-01-02');
  await expect(editor.getByRole('checkbox', { name: /Coffee/ })).toBeChecked();
  await editor.getByRole('button', { name: 'Save meal', exact: true }).click();
  await expect.poll(async () => ((await record(page, 'ironflow_saved_meals')) as any[])?.[0]?.foods.length).toBe(1);
  expect(((await record(page, 'ironflow_saved_meals')) as any[])[0].foods[0].name).toBe('Coffee');
});

